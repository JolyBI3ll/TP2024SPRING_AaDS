/**
@file
@brief Система непересекающихся множеств (DSU)
*/

#ifndef DSU_H
#define DSU_H

#include <vector>

/**
@brief Класс для работы с системой непересекающихся множеств

Реализует Union-Find структуру данных с эвристикой сжатия пути
и объединением по рангу для эффективной работы алгоритма Крускала.
*/
class DSU {
public:
    /**
    @brief Конструктор DSU
    @param count Количество элементов в системе
    */
    explicit DSU(int count);
    
    /**
    @brief Найти представителя множества
    @param v Элемент, для которого ищется представитель
    @return Представитель множества, содержащего элемент v
    */
    int FindParent(int v);
    
    /**
    @brief Объединить два множества
    @param v1 Первый элемент
    @param v2 Второй элемент
    */
    void Union(int v1, int v2);

private:
    std::vector<int> parent;   /**< Массив родителей для каждого элемента */
    std::vector<int> rank;     /**< Массив рангов для оптимизации объединения */
};

#endif // DSU_H