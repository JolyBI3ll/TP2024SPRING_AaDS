/**
@file
@brief Алгоритм Крускала для поиска MST
*/

#ifndef KRUSKAL_ALGORITHM_H
#define KRUSKAL_ALGORITHM_H

#include "igraph.h"
#include "dsu.h"

/**
@brief Реализация алгоритма Крускала для поиска минимального остовного дерева

Алгоритм находит минимальное остовное дерево во взвешенном неориентированном графе
используя систему непересекающихся множеств для эффективной проверки циклов.

@param graph Взвешенный неориентированный граф
@return Суммарный вес минимального остовного дерева

@complexity O(E log E) где E - количество рёбер в графе

@note Граф должен быть неориентированным и связным для корректной работы
*/
int KruskalAlgorithm(const IGraph &graph);

#endif // KRUSKAL_ALGORITHM_H